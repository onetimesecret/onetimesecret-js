#!/usr/bin/env node
// Generates src/generated/v2.ts from spec/openapi.v2.json with openapi-typescript.
//
// The output is committed so consumers and reviewers can read the types without
// running the generator, and so a spec change shows up as a reviewable diff.

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const specPath = join(root, "spec", "openapi.v2.json");
const outPath = join(root, "src", "generated", "v2.ts");

const spec = JSON.parse(await readFile(specPath, "utf8"));
const ast = await openapiTS(spec, {
  // The spec uses `anyOf: [{type}, {type: "null"}]` for nullable fields.
  alphabetize: false,
  exportType: true,
  immutable: false,
  rootTypes: false,
});

const header = [
  "// Generated by scripts/generate-types.mjs from spec/openapi.v2.json.",
  `// Spec: ${spec.info?.title ?? "API v2"} ${spec.info?.version ?? ""}`.trimEnd(),
  "// Do not edit by hand. Run `pnpm generate` after `pnpm sync-spec`.",
  "",
  "/* biome-ignore-all lint: generated code */",
  "",
].join("\n");

await writeFile(outPath, header + astToString(ast));
console.log(`Wrote ${outPath}`);
